import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('signed-in lesson, independent evidence, reload, server gate and account isolation', async ({ page, request }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const signIn = await request.post('/test/session');
  await page.goto(`/#signin=${(await signIn.json()).token}`);
  await expect(page.getByRole('heading', { name: 'Your courses', exact: true })).toBeVisible();
  expect(page.url()).not.toContain('signin=');
  await page.getByRole('button', { name: 'Open course', exact: true }).click();
  await page.getByRole('button', { name: 'Start course', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ordering values', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Continue learning →', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Minimum', exact: true })).toBeVisible();
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(accessibility.violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('connected-lesson.png'), fullPage: true });
  await expect(page.getByRole('button', { name: 'Complete episode →', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Mark this part read', exact: true }).click();
  await page.getByRole('button', { name: 'Start the next check →', exact: true }).click();
  await expect(page.getByText('Which is smaller?', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Continue learning →', exact: true }).click();
  await page.getByRole('button', { name: 'Continue learning →', exact: true }).click();
  await expect(page.getByText('Which is smaller?', { exact: true })).toBeVisible();
  await page.getByRole('radio', { name: '2', exact: true }).click();
  await page.getByRole('button', { name: 'Check answer', exact: true }).click();
  await expect(page.getByText('Correct. 2 is below 5.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Complete episode →', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Start the next check →', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your numeric answer', exact: true }).fill('4');
  await page.getByRole('button', { name: 'Check answer', exact: true }).click();
  await expect(page.getByText('Your independent checks are complete.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Complete episode →', exact: true }).click();
  await expect(page.getByText('1 completed / 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Continue learning →', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Maximum', exact: true })).toBeVisible();
  await expect(page.locator('svg').first()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('connected-visual.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pick up where you left off.', exact: true })).toBeVisible();
  expect(await page.evaluate(async () => (await fetch('/api/enrollments')).status)).toBe(401);
  expect(errors).toEqual([]);
});
